use crate::model::{AiDifficulty, FactionId, MissionArchetype, MutatorId};

#[derive(Debug, Clone, Copy)]
pub struct WaveSpawn {
    pub unit_id: &'static str,
    pub count: usize,
    pub y_offset: f32,
}

#[derive(Debug, Clone, Copy)]
pub struct WaveDef {
    pub trigger_sec: f32,
    pub alert_name: &'static str,
    pub spawns: &'static [WaveSpawn],
}

#[derive(Debug, Clone, Copy)]
pub struct BossAbilityDef {
    pub name: &'static str,
    pub cooldown: f32,
    pub cast_time: f32,
    pub aoe_dmg: f32,
    pub radius: f32,
    pub line_length: f32,
    pub slow_percent: f32,
    pub slow_duration: f32,
    pub poison_dps: f32,
    pub poison_duration: f32,
    pub meteor_count: usize,
    pub color_rgb: [u8; 3],
}

#[derive(Debug, Clone, Copy)]
pub struct BossDef {
    pub name: &'static str,
    pub base_unit_id: &'static str,
    pub scale: f32,
    pub max_hp: f32,
    pub dmg: f32,
    pub rng_studs: f32,
    pub cd: f32,
    pub spd_studs: f32,
    pub melee_dmg_taken_mult: f32,
    pub ranged_dmg_taken_mult: f32,
    pub all_dmg_taken_mult: f32,
    pub flat_dmg_block: f32,
    pub lifesteal_on_hit: f32,
    pub aura_atk_spd: f32,
    pub aura_def: f32,
    pub aura_heal_per_6s: f32,
    pub aura_range_studs: f32,
    pub brood_spawn_interval: Option<f32>,
    pub phase_shift_interval: Option<f32>,
    pub has_phase2_shield: bool,
    pub phase2_shield_amount: f32,
    pub passive_summary: &'static [&'static str],
    pub ability: BossAbilityDef,
}

#[derive(Debug, Clone, Copy)]
pub struct StarCriterion {
    pub stars: u8,
    pub desc: &'static str,
}

#[derive(Debug, Clone, Copy)]
pub struct MissionDef {
    pub id: &'static str,
    pub chapter: u8,
    pub name: &'static str,
    pub territory_name: &'static str,
    pub pin_coord: [f32; 2],
    pub prerequisites: &'static [&'static str],
    pub archetype: MissionArchetype,
    pub enemy_faction: FactionId,
    pub ai_difficulty: AiDifficulty,
    pub starting_gold: f32,
    pub enemy_deck: [&'static str; 6],
    pub briefing: &'static str,
    pub time_limit_seconds: Option<f32>,
    pub player_income_bonus_rate: f32,
    pub waves: &'static [WaveDef],
    pub mutator: Option<MutatorId>,
    pub boss: Option<BossDef>,
    pub star_criteria: [StarCriterion; 3],
    pub reward_blueprints: &'static [&'static str],
    pub unlocks_tier2: bool,
    pub unlocks_tier3: bool,
    pub trophy: Option<&'static str>,
    pub gold_bounty: u32,
    pub mastery_time_limit: f32,
}

